package org.googlebook.pad3.compat;

public final class SystemIdentityAppId {
    public static byte[] forUid(int uid) {
        if (uid != 0 && uid != 1000) return null;
        // AOSP reserves this exact application ID for root and system callers.
        return new byte[] {0x30,0x18,0x31,0x14,0x30,0x12,0x04,0x0d,
                0x41,0x6e,0x64,0x72,0x6f,0x69,0x64,0x53,0x79,0x73,
                0x74,0x65,0x6d,0x02,0x01,0x01,0x31,0x00};
    }
}
